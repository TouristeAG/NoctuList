export function currentLang() {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (SUPPORTED.includes(stored)) return stored;
  const nav = (navigator.language || "fr").slice(0, 2).toLowerCase();
  return SUPPORTED.includes(nav) ? nav : "fr";
}

export function setLang(lang) {
  const next = SUPPORTED.includes(lang) ? lang : "fr";
  localStorage.setItem(STORAGE_KEY, next);
  document.documentElement.lang = next;
  return next;
}

export function locale() {
  return { fr: "fr-CH", en: "en-GB", es: "es", de: "de-CH", it: "it-CH" }[currentLang()] || "fr-CH";
}

export function t(key, vars = {}) {
  const table = T[currentLang()] || T.fr;
  let text = table[key] ?? T.en[key] ?? key;
  Object.entries(vars).forEach(([name, value]) => {
    text = text.replaceAll(`{${name}}`, String(value));
  });
  return text;
}

export function has(key) {
  return Object.prototype.hasOwnProperty.call(T.en, key);
}

/** Fills [data-i18n], [data-i18n-placeholder] and [data-i18n-aria], always as text, never HTML. */
export function applyStaticI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    node.setAttribute("aria-label", t(node.dataset.i18nAria));
  });
  if (window.NoctuTheme) window.NoctuTheme.refreshLabels();
}

export function bindLanguageSelect(select, onChange) {
  select.value = setLang(currentLang());
  applyStaticI18n();
  select.addEventListener("change", () => {
    setLang(select.value);
    applyStaticI18n();
    onChange?.();
  });
}
